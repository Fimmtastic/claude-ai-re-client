// Build pipeline: fonts → CSS bundle → plugin JS → theme → (optional) preview harness.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const vault = path.resolve(root, '../Vault');
const pluginDir = path.join(vault, '.obsidian/plugins/second-brain-core');
const themeDir = path.join(vault, '.obsidian/themes/Second Brain');
const args = new Set(process.argv.slice(2));
const watch = args.has('--watch');
const preview = args.has('--preview');
const prod = !watch;

fs.mkdirSync(pluginDir, { recursive: true });
fs.mkdirSync(themeDir, { recursive: true });

function fontFace(family, file, range, style = 'normal', weight = '100 900') {
  const data = fs.readFileSync(path.join(root, 'node_modules/@fontsource-variable', file)).toString('base64');
  return `@font-face{font-family:'${family}';font-style:${style};font-display:swap;font-weight:${weight};src:url(data:font/woff2;base64,${data}) format('woff2-variations');unicode-range:${range};}`;
}
const LATIN = 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD';
const LATIN_EXT = 'U+0100-02AF,U+0304,U+0308,U+0329,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF';

function buildCss() {
  const fonts = [
    fontFace('SB Inter', 'inter/files/inter-latin-wght-normal.woff2', LATIN),
    fontFace('SB Inter', 'inter/files/inter-latin-ext-wght-normal.woff2', LATIN_EXT),
    fontFace('SB Newsreader', 'newsreader/files/newsreader-latin-wght-normal.woff2', LATIN, 'normal', '200 800'),
    fontFace('SB Newsreader', 'newsreader/files/newsreader-latin-wght-italic.woff2', LATIN, 'italic', '200 800'),
  ].join('\n');
  const order = ['tokens.css', 'base.css', 'components.css', 'pages.css', 'obsidian.css'];
  const css = order.map((f) => `/* ── ${f} ── */\n` + fs.readFileSync(path.join(root, 'src/styles', f), 'utf8')).join('\n');
  const header = '/* Second Brain OS — generated by scripts/build.mjs. Edit src/styles/*.css instead. */\n';
  fs.writeFileSync(path.join(pluginDir, 'styles.css'), header + fonts + '\n' + css);
  fs.copyFileSync(path.join(root, 'src/theme/theme.css'), path.join(themeDir, 'theme.css'));
  fs.writeFileSync(path.join(themeDir, 'manifest.json'), JSON.stringify({ name: 'Second Brain', version: '1.0.0', minAppVersion: '1.5.0', author: 'Second Brain OS' }, null, 2));
  fs.copyFileSync(path.join(root, 'manifest.json'), path.join(pluginDir, 'manifest.json'));
  return header + fonts + '\n' + css;
}

const external = ['obsidian', 'electron', '@codemirror/autocomplete', '@codemirror/collab', '@codemirror/commands', '@codemirror/language', '@codemirror/lint', '@codemirror/search', '@codemirror/state', '@codemirror/view', '@lezer/common', '@lezer/highlight', '@lezer/lr'];

const pluginOpts = {
  entryPoints: [path.join(root, 'src/main.ts')],
  bundle: true,
  external,
  format: 'cjs',
  target: 'es2021',
  platform: 'browser',
  outfile: path.join(pluginDir, 'main.js'),
  sourcemap: prod ? false : 'inline',
  minify: prod,
  treeShaking: true,
  legalComments: 'none',
  banner: { js: '/* Second Brain OS — core plugin. Source: Development/src */' },
  logLevel: 'info',
};

function collectSeed() {
  const seed = {};
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.name.startsWith('.')) continue;
      const p = path.join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.md')) {
        const rel = path.relative(vault, p).split(path.sep).join('/');
        const content = fs.readFileSync(p, 'utf8');
        // honour optional "sbos-mtime" for realistic demo timestamps
        const m = /sbos-mtime:\s*"?(\d{4}-\d{2}-\d{2}[T ][\d:]+)"?/.exec(content);
        const c = /created:\s*"?(\d{4}-\d{2}-\d{2})"?/.exec(content);
        const ctime = c ? new Date(c[1] + 'T09:00:00').getTime() : Date.now() - 86400000 * 3;
        const mtime = m ? new Date(m[1].replace(' ', 'T')).getTime() : ctime;
        seed[rel] = { content, ctime, mtime };
      }
    }
  };
  walk(vault);
  return seed;
}

async function buildPreview(css) {
  const out = path.join(root, 'preview/dist');
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'styles.css'), css + '\n' + fs.readFileSync(path.join(root, 'preview/preview.css'), 'utf8'));
  fs.copyFileSync(path.join(root, 'preview/index.html'), path.join(out, 'index.html'));
  const seed = collectSeed();
  fs.writeFileSync(path.join(out, 'seed.json'), JSON.stringify(seed));
  await esbuild.build({
    entryPoints: [path.join(root, 'preview/preview.ts')],
    bundle: true,
    format: 'iife',
    target: 'es2021',
    outfile: path.join(out, 'app.js'),
    sourcemap: 'inline',
    define: { __SEED__: JSON.stringify(seed) },
    logLevel: 'info',
  });
}

const css = buildCss();
if (watch) {
  const ctx = await esbuild.context(pluginOpts);
  await ctx.watch();
  fs.watch(path.join(root, 'src/styles'), () => { try { buildCss(); console.log('[css] rebuilt'); } catch (e) { console.error(e); } });
  console.log('watching…');
} else {
  await esbuild.build(pluginOpts);
  if (preview) await buildPreview(css);
}
